"""
scripts/seed_db.py
------------------
Seed PostgreSQL database with movies metadata, TMDB information, and 384-dimensional
dense semantic embeddings generated by sentence-transformers.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import logging
import sys
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
from sqlalchemy import select, text

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from backend.database import AsyncSessionLocal, Base, engine
from backend.models.entities import Movie, User
from backend.security import hash_password

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger(__name__)

PROCESSED_DATA_DIR = PROJECT_ROOT / "data" / "processed"
RAW_DATA_DIR = PROJECT_ROOT / "data" / "raw" / "ml-latest-small"
EXTERNAL_DATA_DIR = PROJECT_ROOT / "data" / "external"
ARTIFACTS_DIR = PROJECT_ROOT / "artifacts"


async def seed_database(limit: int | None = None, batch_size: int = 500) -> None:
    """Populate movies and dense embeddings into PostgreSQL."""
    logger.info("Initializing database schema if not already present...")
    async with engine.begin() as conn:
        # Enable pgvector if on PostgreSQL
        if conn.dialect.name == "postgresql":
            await conn.execute(text("CREATE EXTENSION IF NOT EXISTS vector;"))
        await conn.run_sync(Base.metadata.create_all)

    # 1. Load movies cleaned data
    movies_path = PROCESSED_DATA_DIR / "movies_cleaned.parquet"
    if not movies_path.exists():
        raise FileNotFoundError(f"movies_cleaned.parquet not found at {movies_path}")
    movies_df = pd.read_parquet(movies_path)

    # 2. Load embeddings
    embeddings_path = ARTIFACTS_DIR / "movie_embeddings.npy"
    if not embeddings_path.exists():
        raise FileNotFoundError(f"movie_embeddings.npy not found at {embeddings_path}")
    embeddings = np.load(embeddings_path)
    logger.info(f"Loaded embeddings shape: {embeddings.shape}")

    # 3. Load links for tmdbId mapping
    links_path = RAW_DATA_DIR / "links.csv"
    mid_to_tmdb: dict[int, int] = {}
    if links_path.exists():
        links_df = pd.read_csv(links_path)
        for _, row in links_df.dropna(subset=["tmdbId"]).iterrows():
            mid_to_tmdb[int(row["movieId"])] = int(row["tmdbId"])

    # 4. Load TMDB cache for overview, poster_path
    tmdb_cache_path = EXTERNAL_DATA_DIR / "tmdb_cache.json"
    tmdb_cache: dict[str, dict[str, Any]] = {}
    if tmdb_cache_path.exists():
        try:
            with open(tmdb_cache_path, encoding="utf-8") as f:
                tmdb_cache = json.load(f)
        except Exception as e:
            logger.warning(f"Could not read tmdb_cache: {e}")

    # 5. Connect and insert
    async with AsyncSessionLocal() as session:
        # Check existing movies count
        count_res = await session.execute(select(Movie.id).limit(1))
        existing_movie = count_res.first()
        if existing_movie is not None:
            logger.info("Database already contains movies. Skipping duplicate insertion.")
        else:
            total_movies = len(movies_df) if limit is None else min(limit, len(movies_df))
            logger.info(f"Inserting {total_movies} movies into database...")

            movies_to_insert: list[Movie] = []
            for idx in range(total_movies):
                row = movies_df.iloc[idx]
                mid = int(row["movieId"])
                title = str(row.get("clean_title") or row.get("title") or "").strip()
                yr = int(row["year"]) if pd.notna(row.get("year")) else None

                genres_val = row.get("genres", [])
                genres_list = (
                    list(genres_val)
                    if isinstance(genres_val, list | np.ndarray)
                    else [str(genres_val)]
                )

                tmdb_id = mid_to_tmdb.get(mid)
                cache_meta = tmdb_cache.get(str(mid), {})
                overview = cache_meta.get("overview") or None
                poster_path = cache_meta.get("poster_path") or None

                emb_vec = embeddings[idx].tolist() if idx < len(embeddings) else None

                movie = Movie(
                    ml_movie_id=mid,
                    tmdb_id=tmdb_id,
                    title=title,
                    year=yr,
                    genres=genres_list,
                    overview=overview,
                    poster_path=poster_path,
                    embedding=emb_vec,
                )
                movies_to_insert.append(movie)

                if len(movies_to_insert) >= batch_size:
                    session.add_all(movies_to_insert)
                    await session.commit()
                    logger.info(f"Inserted {idx + 1}/{total_movies} movies...")
                    movies_to_insert = []

            if movies_to_insert:
                session.add_all(movies_to_insert)
                await session.commit()
                logger.info(f"Inserted all {total_movies} movies.")

        # Seed sample demo user
        user_res = await session.execute(select(User).where(User.email == "demo@cinematch.ai"))
        if user_res.scalar_one_or_none() is None:
            logger.info("Creating default demo user: demo@cinematch.ai...")
            demo_user = User(
                email="demo@cinematch.ai",
                hashed_password=hash_password("Password123!"),
            )
            session.add(demo_user)
            await session.commit()
            logger.info("Created default demo user (demo@cinematch.ai / Password123!)")

    logger.info("Database seeding completed successfully.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Seed CineMatch database with movies and vector embeddings."
    )
    parser.add_argument("--limit", type=int, default=None, help="Limit number of movies to insert.")
    parser.add_argument("--batch-size", type=int, default=500, help="Batch insertion size.")
    args = parser.parse_args()

    asyncio.run(seed_database(limit=args.limit, batch_size=args.batch_size))
